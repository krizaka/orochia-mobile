import { describe, expect, it } from "@jest/globals";
import fs from "fs";
import path from "path";

const FIXTURES = path.resolve(__dirname, "../__fixtures__/api");
const OROCHIA_PEOPLE = "https://krizaka-assets.b-cdn.net/site/people/orochia/";

/** Every value of an avatar field, at any depth. */
function avatars(value: unknown, out: string[] = []): string[] {
  if (Array.isArray(value)) value.forEach((v) => avatars(v, out));
  else if (value && typeof value === "object") {
    for (const [key, v] of Object.entries(value)) {
      if (/avatar/i.test(key) && typeof v === "string") out.push(v);
      else avatars(v, out);
    }
  }
  return out;
}

// One face = one persona = one product: Orochia's people wear Orochia's own portraits (generated by Orazaka, on the
// Krizaka CDN) — never a stock photo of a real person, never another product's face.
describe("the faces in the API fixtures", () => {
  const files = fs.readdirSync(FIXTURES).filter((f) => f.endsWith(".json"));

  it("are Orochia's own portraits", () => {
    const found = files.flatMap((f) => avatars(JSON.parse(fs.readFileSync(path.join(FIXTURES, f), "utf8"))));
    expect(found.length).toBeGreaterThan(0);
    for (const url of found) expect(url.startsWith(OROCHIA_PEOPLE)).toBe(true);
  });
});
